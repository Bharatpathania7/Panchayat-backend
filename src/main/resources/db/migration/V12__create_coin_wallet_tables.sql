-- =====================================================
-- 1. USER COIN WALLETS
-- =====================================================

CREATE TABLE coin_wallets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id BIGINT NOT NULL UNIQUE,

    balance BIGINT NOT NULL DEFAULT 0
        CHECK (balance >= 0),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_coin_wallets_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE RESTRICT
);


-- =====================================================
-- 2. COIN TRANSACTIONS
-- =====================================================

CREATE TABLE coin_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id BIGINT NOT NULL,

    transaction_type VARCHAR(10) NOT NULL
        CHECK (transaction_type IN ('CREDIT', 'DEBIT')),

    amount BIGINT NOT NULL
        CHECK (amount > 0),

    balance_before BIGINT NOT NULL
        CHECK (balance_before >= 0),

    balance_after BIGINT NOT NULL
        CHECK (balance_after >= 0),

    reason VARCHAR(40) NOT NULL,

    reference_id VARCHAR(100),

    description VARCHAR(500),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_coin_transactions_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE RESTRICT,

    CONSTRAINT chk_coin_transaction_balance
        CHECK (
            (
                transaction_type = 'CREDIT'
                AND balance_after = balance_before + amount
            )
            OR
            (
                transaction_type = 'DEBIT'
                AND balance_after = balance_before - amount
            )
        )
);


-- =====================================================
-- 3. INDEXES
-- =====================================================

CREATE INDEX idx_coin_transactions_user_created
    ON coin_transactions (user_id, created_at DESC);

CREATE INDEX idx_coin_transactions_reason
    ON coin_transactions (reason);