
CREATE TABLE coin_packs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    name VARCHAR(100) NOT NULL,
    coins BIGINT NOT NULL CHECK (coins > 0),

    price_in_rupees NUMERIC(10, 2) NOT NULL
        CHECK (price_in_rupees > 0),

    bonus_coins BIGINT NOT NULL DEFAULT 0
        CHECK (bonus_coins >= 0),

    bonus_percentage INTEGER NOT NULL DEFAULT 0
        CHECK (bonus_percentage BETWEEN 0 AND 100),

    badge VARCHAR(30),

    image_url VARCHAR(1000),
    image_public_id VARCHAR(255),

    active BOOLEAN NOT NULL DEFAULT TRUE,

    sort_order INTEGER NOT NULL DEFAULT 0
        CHECK (sort_order >= 0),

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_coin_packs_active_sort
    ON coin_packs (active, sort_order);
