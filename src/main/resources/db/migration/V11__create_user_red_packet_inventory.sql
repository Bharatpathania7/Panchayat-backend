CREATE TABLE user_red_packet_inventory (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id BIGINT NOT NULL,
    red_packet_product_id BIGINT NOT NULL,

    quantity BIGINT NOT NULL DEFAULT 0
        CHECK (quantity >= 0),

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_red_packet_inventory_user
        FOREIGN KEY (user_id) REFERENCES users(id),

    CONSTRAINT fk_red_packet_inventory_product
        FOREIGN KEY (red_packet_product_id)
        REFERENCES red_packet_products(id),

    CONSTRAINT uk_user_red_packet_inventory
        UNIQUE (user_id, red_packet_product_id)
);

CREATE INDEX idx_red_packet_inventory_user
    ON user_red_packet_inventory(user_id);