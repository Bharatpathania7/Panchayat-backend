CREATE TABLE payment_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,


    txn_id VARCHAR(100) NOT NULL UNIQUE,

    user_id BIGINT NOT NULL
        REFERENCES users(id) ON DELETE RESTRICT,

    purpose VARCHAR(30) NOT NULL
        CHECK (purpose IN ('COIN_PACK', 'RED_PACKET', 'VIP')),

    product_id BIGINT,

    amount NUMERIC(10, 2) NOT NULL
        CHECK (amount > 0),

    currency VARCHAR(3) NOT NULL DEFAULT 'INR'
        CHECK (currency = 'INR'),

    status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'SUCCESS', 'FAILED')),

    payu_payment_id VARCHAR(100),

    payment_mode VARCHAR(50),

    failure_reason VARCHAR(500),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    verified_at TIMESTAMPTZ,

    CONSTRAINT chk_payment_product_id
        CHECK (product_id IS NULL OR product_id > 0)
);

CREATE INDEX idx_payment_transactions_user_created
    ON payment_transactions (user_id, created_at DESC);

CREATE INDEX idx_payment_transactions_status_created
    ON payment_transactions (status, created_at);

CREATE INDEX idx_payment_transactions_purpose_product
    ON payment_transactions (purpose, product_id);