
CREATE TABLE red_packet_products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    coin_value BIGINT NOT NULL CHECK (coin_value > 0),
    price_in_rupees NUMERIC(10, 2) NOT NULL CHECK (price_in_rupees > 0),
    image_url VARCHAR(1000),
    image_public_id VARCHAR(255),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order INTEGER NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_red_packet_products_active_sort
    ON red_packet_products (active, sort_order);
